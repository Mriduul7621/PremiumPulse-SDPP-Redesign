function parseTable(raw: string): RateMap {
  const result: RateMap = {};
  const lines = raw.trim().split('\n');
  for (const line of lines) {
    const parts = line.trim().split(/\s+/);
    if (parts.length > 1) {
      const age = parseInt(parts[0], 10);
      const values = parts.slice(1).map(Number);
      result[age] = values;
    }
  }
  return result;
}

const CI_CLASSIC_MALE: RateMap = parseTable(CLASSIC_MALE_RAW);
const CI_CLASSIC_FEMALE: RateMap = parseTable(CLASSIC_FEMALE_RAW);
const CI_STANDARD_MALE: RateMap = parseTable(STANDARD_MALE_RAW);
const CI_STANDARD_FEMALE: RateMap = parseTable(STANDARD_FEMALE_RAW);

export function getCIRate(age: number, term: number, gender: 'Male' | 'Female', type: 'Classic' | 'Standard'): number {
  let table: RateMap;
  if (type === 'Classic') {
    table = gender === 'Male' ? CI_CLASSIC_MALE : CI_CLASSIC_FEMALE;
  } else {
    table = gender === 'Male' ? CI_STANDARD_MALE : CI_STANDARD_FEMALE;
  }

  // Handle boundary parameters gracefully
  const targetAge = Math.max(18, Math.min(60, age));
  const row = table[targetAge];

  if (!row) {
    return 1.0; // Fail-safe default
  }

  // The policy age + term cannot exceed 70.
  // Clamp term between 1 and min(20, 70 - targetAge)
  const maxTerm = Math.min(20, 70 - targetAge);
  const targetTerm = Math.max(1, Math.min(maxTerm, term));

  const val = row[targetTerm - 1];
  return val !== undefined ? val : 1.0;
}
